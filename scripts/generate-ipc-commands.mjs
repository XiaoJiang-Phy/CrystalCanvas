import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { create_inventory } from './ipc-inventory.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const CLASSIFICATION = resolve(ROOT, 'ipc/command-classification.json');
const EVENT_CLASSIFICATION = resolve(ROOT, 'ipc/event-classification.json');
const OUTPUT = resolve(ROOT, 'src/ipc/commands.generated.ts');

const classification = JSON.parse(await readFile(CLASSIFICATION, 'utf8')).commands;
const eventClassification = JSON.parse(await readFile(EVENT_CLASSIFICATION, 'utf8')).events;
const commands = Object.keys(classification).sort();
const events = Object.keys(eventClassification).sort();
const { backend_command_args } = await create_inventory();
const missing = commands.filter((command) => !Object.hasOwn(backend_command_args, command));
if (missing.length > 0) throw new Error(`Missing Rust argument schema: ${missing.join(', ')}`);

const content = `// Generated by scripts/generate-ipc-commands.mjs. Do not edit manually.\n\nexport type { FieldLayerInfo, FieldLineageTerm, FieldLinearCombinationTerm, FieldSceneChangedPayload, FieldSceneInfo } from './contracts';\n\nexport const IPC_COMMANDS = {\n${commands.map((command) => `    ${command}: '${command}',`).join('\n')}\n} as const;\n\nexport const IPC_COMMAND_CLASSIFICATION = {\n${commands.map((command) => `    ${command}: '${classification[command]}',`).join('\n')}\n} as const;\n\nexport const IPC_EVENTS = {\n${events.map((event) => `    '${event}': '${event}',`).join('\n')}\n} as const;\n\nexport const IPC_EVENT_CLASSIFICATION = {\n${events.map((event) => `    '${event}': '${eventClassification[event]}',`).join('\n')}\n} as const;\n\nexport type IpcCommandName = typeof IPC_COMMANDS[keyof typeof IPC_COMMANDS];\nexport type IpcEventName = typeof IPC_EVENTS[keyof typeof IPC_EVENTS];\nexport type ReadIpcCommand = {\n    [Command in IpcCommandName]: typeof IPC_COMMAND_CLASSIFICATION[Command] extends 'read' ? Command : never;\n}[IpcCommandName];\n`;

if (process.argv.includes('--check')) {
    const existing = await readFile(OUTPUT, 'utf8');
    if (existing !== content) {
        throw new Error('src/ipc/commands.generated.ts is stale; run npm run generate:ipc');
    }
} else {
    await writeFile(OUTPUT, content);
}
